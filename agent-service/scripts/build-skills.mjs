// Bundles the extra agent skills into the Worker and the plugin.
//
// Source of truth: agent/skills/<name>/*.md. This writes
//   agent-service/skills.generated.mjs        what the MCP server serves
//   plugin/launch-archive/skills/<name>/      what the plugin installs
// Run it after editing a skill: `npm run build:skills`. A test fails when the
// generated module is out of step with the sources.
import {readdir, readFile, writeFile, mkdir, rm} from 'node:fs/promises';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const SOURCE = join(root, 'agent', 'skills');
const OUT = join(here, '..', 'skills.generated.mjs');
const PLUGIN = join(root, 'plugin', 'launch-archive', 'skills');

export async function readSkills(source = SOURCE) {
  const skills = {};
  for (const name of (await readdir(source, {withFileTypes:true})).filter(d => d.isDirectory()).map(d => d.name).sort()) {
    const files = {};
    for (const file of (await readdir(join(source, name))).filter(f => f.endsWith('.md')).sort())
      files[file] = (await readFile(join(source, name, file), 'utf8')).replace(/\r\n/g, '\n');
    if (!files['SKILL.md']) throw new Error(`agent/skills/${name} has no SKILL.md`);
    skills[name] = files;
  }
  return skills;
}

export const render = skills => `// Generated by scripts/build-skills.mjs from agent/skills. Do not edit.\nexport const EXTRA_SKILLS = ${JSON.stringify(skills, null, 2)};\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const skills = await readSkills();
  await writeFile(OUT, render(skills));
  for (const [name, files] of Object.entries(skills)) {
    await rm(join(PLUGIN, name), {recursive:true, force:true});
    await mkdir(join(PLUGIN, name), {recursive:true});
    for (const [file, text] of Object.entries(files)) await writeFile(join(PLUGIN, name, file), text);
  }
  console.log(`Bundled ${Object.keys(skills).join(', ')}`);
}
