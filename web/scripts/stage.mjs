// Builds the gallery data with ../scripts/build_site.py and stages the data and
// static assets (videos.json, daily-stats.json, llms.txt, favicons, logos, ...) into
// public/. The pages, stylesheet and scripts are NOT staged: Astro owns them now
// (src/pages, src/styles, src/scripts). Staging the old copies would collide with the
// Astro routes and serve stale duplicates.
// MP4s go to ../site-public for scripts/sync_media_r2.py, never into the Worker.
import { execFileSync } from 'node:child_process';
import { cpSync, rmSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(web, '..');
const generated = path.join(web, '.generated');
const env = {
  ...process.env,
  PYTHONUTF8: '1',
  KUCHI_BASE_URL: process.env.KUCHI_BASE_URL ?? 'https://kuchi.kalarislabs.com',
  KUCHI_MEDIA_URL: process.env.KUCHI_MEDIA_URL ?? 'https://kuchi-media.kalarislabs.com',
};
const python = process.env.PYTHON ?? (process.platform === 'win32' ? 'python' : 'python3');
rmSync(generated, { recursive: true, force: true });
execFileSync(python, ['scripts/build_site.py', '--output', generated, '--media-dir', path.join(root, 'site-public')],
  { cwd: root, env, stdio: 'inherit' });
rmSync(path.join(web, 'public'), { recursive: true, force: true });
mkdirSync(path.join(web, 'public'));
// Top-level files of the old site that Astro now renders or bundles itself.
const MIGRATED = new Set([
  'index.html', 'privacy.html', 'terms.html', 'support.html',
  'style.css', 'app.js', 'connect.js', 'analytics.mjs', 'analytics-events.mjs', 'daily-stats.mjs',
]);
cpSync(generated, path.join(web, 'public'), {
  recursive: true,
  filter: (src) => !(path.dirname(src) === generated && MIGRATED.has(path.basename(src))),
});

const skillMd = readFileSync(path.join(root, 'agent', 'SKILL.md'), 'utf8');
const workflowMd = readFileSync(path.join(root, 'agent', 'workflow.md'), 'utf8');
const skillDataTs = `// Auto-generated by scripts/stage.mjs - do not edit directly
export const SKILL_MD = ${JSON.stringify(skillMd)};
export const WORKFLOW_MD = ${JSON.stringify(workflowMd)};
`;
writeFileSync(path.join(web, 'src', 'lib', 'skill-data.ts'), skillDataTs, 'utf8');

console.log('Staged gallery into web/public and generated skill-data.ts');
